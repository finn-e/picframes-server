def _set_pixel(buf, x, y, color, width=800):
    if x < 0 or x >= width or y < 0 or y >= 480:
        return
    idx = (y * width + x) // 2
    b = buf[idx]
    if x % 2 == 0:
        buf[idx] = (b & 0x0F) | (color << 4)
    else:
        buf[idx] = (b & 0xF0) | color

def _render_text_line(buf, text, y, scale=1, color=COL_BLACK, width=800):
    char_w = 5
    spacing = 1
    total_w = len(text) * (char_w + spacing) * scale
    x_off = max(0, (width - total_w) // 2)
    for ch in text:
        glyph = FONT.get(ch.upper(), FONT.get(' ', (0,0,0,0,0)))
        for ci in range(5):
            col_val = glyph[ci]
            for ri in range(7):
                if col_val & (1 << ri):
                    for sx in range(scale):
                        for sy in range(scale):
                            _set_pixel(buf, x_off + ci*scale + sx, y + ri*scale + sy, color)
        x_off += (char_w + spacing) * scale

def apply_battery_square(buf, battery_pct):
    """
    Renders a 4x4 solid colored square 4px from bottom-right.
    <20% triggers critical low-battery red banner.
    """
    if battery_pct is None:
        battery_pct = 100
    if battery_pct >= 80:
        color = COL_GREEN
    elif battery_pct >= 60:
        color = COL_YELLOW
    elif battery_pct >= 40:
        color = COL_ORANGE
    elif battery_pct >= 20:
        color = COL_RED
    else:
        _apply_critical_battery_banner(buf)
        return
    for dy in range(BAT_SQ_SIZE):
        for dx in range(BAT_SQ_SIZE):
            _set_pixel(buf, BAT_SQ_X + dx, BAT_SQ_Y + dy, color)

def _apply_critical_battery_banner(buf):
    BANNER_H = 32
    BANNER_Y = 480 - BANNER_H
    for y in range(BANNER_Y, 480):
        for x in range(800):
            _set_pixel(buf, x, y, COL_RED)
    msg = 'LOW BATTERY: PLEASE PLUG INTO POWER'
    _render_text_line(buf, msg, BANNER_Y + (BANNER_H - 14) // 2, scale=1, color=COL_WHITE)

def apply_branding_text(buf):
    """Renders 'PicFrames/CONNECTED DISPLAY' at bottom edge."""
    msg = 'PICFRAMES/CONNECTED DISPLAY'
    _render_text_line(buf, msg, 480 - 8, scale=1, color=COL_BLACK)
